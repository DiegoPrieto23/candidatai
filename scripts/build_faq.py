"""Genera las preguntas frecuentes de `docs/` desde los textos de la ayuda del portal.

Uso (desde la raíz): uv run --no-project python scripts/build_faq.py [--check]

Las preguntas se escriben una sola vez, en `frontend/src/locales/<idioma>/help.json` (el texto) y
`frontend/src/lib/helpTopics.json` (el orden, el grupo y la pantalla de cada una): el portal las
enseña en su panel de ayuda y este script las pasa a `docs/PREGUNTAS.md` (español) y `docs/FAQ.md`
(inglés). Así la ayuda de la app y la de la documentación dicen lo mismo.

- sin opciones, escribe los dos ficheros;
- con `--check`, no escribe nada y falla (código 1) si alguno no está al día. Lo usa la CI.
"""

from __future__ import annotations

import json
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
TOPICS = Path("frontend/src/lib/helpTopics.json")
LOCALES = Path("frontend/src/locales")


@dataclass(frozen=True)
class Page:
    language: str
    path: str
    title: str
    switch: str
    intro: str
    where: str
    generated: str


PAGES = (
    Page(
        language="es",
        path="docs/PREGUNTAS.md",
        title="Preguntas frecuentes",
        switch="[English](FAQ.md) · **Español**",
        intro=(
            "Las dudas más habituales al usar CandidatAI, con la pantalla donde se resuelve cada "
            "una. Son las mismas que busca el botón de ayuda de la app, abajo a la derecha (se "
            "abre con `?`). Para el detalle, la [guía de uso](GUIA.md); si es tu primera vez, "
            "[Empieza aquí](EMPEZAR.md)."
        ),
        where="Dónde: «{screen}».",
        generated=(
            "<!-- Generado por scripts/build_faq.py desde frontend/src/locales/es/help.json. "
            "No lo edites a mano. -->"
        ),
    ),
    Page(
        language="en",
        path="docs/FAQ.md",
        title="Frequent questions",
        switch="**English** · [Español](PREGUNTAS.md)",
        intro=(
            "The most common questions when using CandidatAI, with the screen where each one is "
            "sorted out. They are the same ones the app's help button searches, at the bottom "
            "right (it opens with `?`). For the detail, see the [user guide](GUIDE.md); if this "
            "is your first time, [Start here](START_HERE.md)."
        ),
        where="Where: “{screen}”.",
        generated=(
            "<!-- Generated by scripts/build_faq.py from frontend/src/locales/en/help.json. "
            "Do not edit by hand. -->"
        ),
    ),
)


def _read(root: Path, path: Path) -> dict[str, Any]:
    data = json.loads((root / path).read_text(encoding="utf-8"))
    assert isinstance(data, dict)
    return data


def render(root: Path, page: Page) -> str:
    topics = _read(root, TOPICS)
    texts = _read(root, LOCALES / page.language / "help.json")
    lines = [f"# {page.title}", "", page.switch, "", page.generated, "", page.intro, ""]
    for group in topics["groups"]:
        lines += [f"## {texts['groups'][group]}", ""]
        for topic in topics["topics"]:
            if topic["group"] != group:
                continue
            entry = texts["faq"][topic["id"]]
            lines += [f"### {entry['q']}", "", entry["a"]]
            if topic["screen"] is not None:
                lines += ["", page.where.format(screen=texts["screens"][topic["screen"]])]
            lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def outdated(root: Path) -> list[str]:
    """Los ficheros que no coinciden con lo que saldría ahora."""
    stale = []
    for page in PAGES:
        target = root / page.path
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if current != render(root, page):
            stale.append(page.path)
    return stale


def main(argv: list[str]) -> int:
    if "--check" in argv:
        stale = outdated(ROOT)
        for path in stale:
            print(f"{path} no está al día: ejecuta scripts/build_faq.py")
        return 1 if stale else 0
    for page in PAGES:
        (ROOT / page.path).write_text(render(ROOT, page), encoding="utf-8", newline="\n")
        print(f"{page.path} escrito")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
